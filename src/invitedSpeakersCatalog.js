const allEntries = () => {
  return [
    ...plenarySpeakers.map((s) => ({ ...s, tier: "plenary" })),
    ...invitedCongressSpeakers.map((s) => ({ ...s, tier: "congress" })),
  ];
};

/** @type {Set<string>} */
const keySet = new Set(allEntries().map((s) => s.key));

export function isValidInvitedSpeakerKey(key) {
  return typeof key === "string" && keySet.has(key);
}

export function getInvitedSpeakerByKey(key) {
  for (const s of allEntries()) {
    if (s.key === key) return s;
  }
  return null;
}

export function allInvitedSpeakerKeys() {
  return Array.from(keySet);
}
